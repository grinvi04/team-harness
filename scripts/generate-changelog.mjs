#!/usr/bin/env node

import { execFileSync } from 'node:child_process'
import { lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const marker = '<!-- Generated by scripts/generate-changelog.mjs. Do not edit. -->'
const legacyMarker = '<!-- Generated file. Do not edit release entries manually. -->'
const version = /^v\d+\.\d+\.\d+$/
const maximumLines = 199
const bodyCapacity = maximumLines - 4

function argumentsFor(argv) {
  const options = { release: '', mode: 'stdout', output: root }
  const seen = new Set()
  for (let i = 0; i < argv.length; i++) {
    const option = argv[i]
    if (!['--release', '--write', '--check', '--output'].includes(option) || seen.has(option)) throw new Error('usage')
    seen.add(option)
    if (option === '--write' || option === '--check') {
      if (options.mode !== 'stdout') throw new Error('usage')
      options.mode = option.slice(2)
    } else {
      const value = argv[++i]
      if (!value || value.startsWith('--')) throw new Error('usage')
      if (option === '--release') {
        if (!version.test(value)) throw new Error('usage')
        options.release = value
      } else options.output = path.resolve(value)
    }
  }
  if (seen.has('--output') && options.mode === 'stdout') throw new Error('usage')
  return options
}

function git(args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

function releasesFromGit(candidate) {
  const tags = git(['tag', '--list', 'v*', '--sort=-version:refname']).trim().split('\n').filter(Boolean)
  const invalid = tags.filter((tag) => !version.test(tag))
  if (invalid.length) throw new Error(`invalid version tag(s): ${invalid.join(', ')}`)
  const candidateIndex = candidate ? tags.indexOf(candidate) : -1
  const candidateExists = candidateIndex >= 0
  const releases = [
    ...(candidate ? [{
      tag: candidate, ref: candidateExists ? candidate : 'HEAD',
      older: candidateExists ? tags[candidateIndex + 1] : tags[0], isCandidate: true,
    }] : []),
    ...tags.filter((tag) => tag !== candidate).map((tag) => ({
      tag, ref: tag, older: tags[tags.indexOf(tag) + 1], isCandidate: false,
    })),
  ]
  return releases.flatMap(({ tag, ref, older, isCandidate }) => {
    const range = older ? `${older}..${ref}` : ref
    // NUL pairs preserve literal subjects. %s deliberately excludes commit bodies,
    // matching the original generator's subject-only history contract.
    const records = git(['log', '-z', '--format=%cs%x00%s', range]).split('\0')
    const entries = []
    for (let i = 0; i + 1 < records.length; i += 2) {
      const [date, subject] = [records[i], records[i + 1]]
      if (/^(feat|fix)(\([^)]+\))?!?: /.test(subject)) entries.push({ date, subject })
    }
    if (!entries.length) return []
    const date = isCandidate ? entries[0].date : git(['log', '-1', '--format=%cs', ref]).trim()
    return [{ tag, date, entries: entries.map(({ subject }) => `- ${subject}`) }]
  })
}

function generatedFiles(releases, candidate) {
  const files = new Map()
  function page(file, title, body) {
    const lines = [`# ${title}`, '', marker, '', ...body]
    if (lines.length > maximumLines) throw new Error(`generated page exceeds ${maximumLines} lines: ${file}`)
    files.set(file, `${lines.join('\n')}\n`)
  }
  function link(from, to, label) {
    return `- [${label}](${path.posix.relative(path.posix.dirname(from), to)})`
  }
  // Paginate indexes too: even a release with more than 195 entry chunks has
  // bounded ancestor pages, while link traversal keeps the original order.
  function index(file, title, destinations, introduction = [], level = 1) {
    if (destinations.length + introduction.length <= bodyCapacity) {
      page(file, title, [...introduction, ...destinations.map(({ file: target, label }) => link(file, target, label))])
      return
    }
    const stem = file.slice(0, -3)
    const pages = []
    for (let offset = 0; offset < destinations.length; offset += bodyCapacity) {
      const end = Math.min(offset + bodyCapacity, destinations.length)
      const child = `${stem}/index-${level}-${String(pages.length + 1).padStart(3, '0')}.md`
      index(child, `${title} — ${offset + 1}–${end}`, destinations.slice(offset, end))
      pages.push({ file: child, label: `${title} — ${offset + 1}–${end}` })
    }
    index(file, title, pages, introduction, level + 1)
  }
  const releaseLinks = []
  for (const { tag, date, entries } of releases) {
    const title = `${tag} - ${date}`
    const file = `docs/changelog/${date.slice(0, 4)}/${tag}.md`
    releaseLinks.push({ file, label: title })
    if (entries.length <= bodyCapacity) page(file, title, entries)
    else {
      const entryPages = []
      for (let offset = 0; offset < entries.length; offset += bodyCapacity) {
        const end = Math.min(offset + bodyCapacity, entries.length)
        const child = `${file.slice(0, -3)}/entries-${String(entryPages.length + 1).padStart(3, '0')}.md`
        page(child, `${title} — entries ${offset + 1}–${end}`, entries.slice(offset, end))
        entryPages.push({ file: child, label: `Entries ${offset + 1}–${end}` })
      }
      index(file, title, entryPages, ['Release entries retain their original Git log order.', ''])
    }
  }
  index('docs/changelog/releases.md', 'Releases', releaseLinks,
    releaseLinks.length ? [] : ['No version release contains a `feat` or `fix` entry.'])
  const command = `node scripts/generate-changelog.mjs${candidate ? ` --release ${candidate}` : ''} --write`
  page('CHANGELOG.md', 'Changelog', [
    candidate
      ? 'Generated from version tags, a pre-tag release candidate, and Conventional Commits (`feat` and `fix` only).'
      : 'Generated from version tags and Conventional Commits (`feat` and `fix` only).',
    `Regenerate the complete index and release tree with \`${command}\`.`,
    '', link('CHANGELOG.md', 'docs/changelog/releases.md', 'Release history'),
  ])
  return files
}

function owned(content, file) {
  return content.split('\n').includes(marker)
    || (file === 'CHANGELOG.md' && content.startsWith(`# Changelog\n\n${legacyMarker}\n`))
}

function stat(file) {
  try { return lstatSync(file) }
  catch (error) { if (error.code !== 'ENOENT') throw error; return null }
}

function checkedOutput(output, files) {
  const existing = new Map()
  function directory(file) {
    const entry = stat(file)
    if (!entry) return false
    if (!entry.isDirectory() || entry.isSymbolicLink()) throw new Error(`unsupported output directory: ${file}`)
    return true
  }
  function read(file, relative) {
    const entry = stat(file)
    if (!entry) return
    if (!entry.isFile() || entry.isSymbolicLink()) throw new Error(`unsupported output entry: ${file}`)
    const content = readFileSync(file, 'utf8')
    if (files.has(relative) && !owned(content, relative)) throw new Error(`refusing to overwrite user file: ${relative}`)
    if (owned(content, relative)) existing.set(relative, content)
  }
  function visit(file, relative) {
    if (!directory(file)) return
    for (const entry of readdirSync(file, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const child = path.join(file, entry.name)
      const name = path.posix.join(relative, entry.name)
      if (entry.isDirectory()) visit(child, name)
      else read(child, name)
    }
  }
  if (!directory(output)) return existing
  read(path.join(output, 'CHANGELOG.md'), 'CHANGELOG.md')
  if (directory(path.join(output, 'docs'))) visit(path.join(output, 'docs/changelog'), 'docs/changelog')
  // Preflight the entire tree before any write so a later collision cannot cause
  // an earlier generated file to be replaced. Symlinks (including dangling ones) fail.
  for (const file of files.keys()) {
    const parts = file.split('/')
    for (let i = 1; i < parts.length; i++) directory(path.join(output, ...parts.slice(0, i)))
    const entry = stat(path.join(output, file))
    if (entry && (!entry.isFile() || entry.isSymbolicLink())) throw new Error(`unsupported output entry: ${file}`)
  }
  return existing
}

function synchronize(options, files) {
  const existing = checkedOutput(options.output, files)
  const stale = [...existing.keys()].filter((file) => !files.has(file))
  const changed = [...files].filter(([file, content]) => existing.get(file) !== content).map(([file]) => file)
  if (options.mode === 'check') {
    if (changed.length || stale.length) {
      for (const file of changed) console.error(`changelog differs or is missing: ${file}`)
      for (const file of stale) console.error(`stale generated changelog: ${file}`)
      return 1
    }
    console.log(`OK changelog files=${files.size}`)
    return 0
  }
  for (const [file, content] of files) {
    const target = path.join(options.output, file)
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, content)
  }
  const staleDirectories = new Set()
  for (const file of stale) {
    rmSync(path.join(options.output, file))
    let directory = path.posix.dirname(file)
    while (directory.startsWith('docs/changelog/')) {
      staleDirectories.add(directory)
      directory = path.posix.dirname(directory)
    }
  }
  // Only prune empty ancestors of stale generated files; user-created empty
  // directories are as unrelated to this command as user-authored files.
  for (const relative of [...staleDirectories].sort((a, b) => b.length - a.length)) {
    const directory = path.join(options.output, relative)
    if (readdirSync(directory).length === 0) rmSync(directory, { recursive: true })
  }
  console.log(`OK changelog files=${files.size} output=${options.output}`)
  return 0
}

try {
  const options = argumentsFor(process.argv.slice(2))
  const files = generatedFiles(releasesFromGit(options.release), options.release)
  if (options.mode === 'stdout') process.stdout.write(files.get('CHANGELOG.md'))
  else process.exitCode = synchronize(options, files)
} catch (error) {
  if (error.message === 'usage') {
    console.error('usage: node scripts/generate-changelog.mjs [--release vMAJOR.MINOR.PATCH] [--write|--check [--output directory]]')
    process.exitCode = 2
  } else {
    console.error(`generate-changelog: ${error.message}`)
    process.exitCode = 1
  }
}
