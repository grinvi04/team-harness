#!/usr/bin/env node

import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const temporary = mkdtempSync(path.join(os.tmpdir(), 'harness-changelog-test-'))
let sequence = 0
let passed = 0
let failed = 0
const marker = '<!-- Generated by scripts/generate-changelog.mjs. Do not edit. -->'

function git(repo, args, env = {}) {
  return execFileSync('git', args, { cwd: repo, encoding: 'utf8', env: { ...process.env, ...env } }).trim()
}

function fixture() {
  const repo = path.join(temporary, `repo-${++sequence}`)
  mkdirSync(path.join(repo, 'scripts'), { recursive: true })
  copyFileSync(path.join(root, 'scripts/generate-changelog.mjs'), path.join(repo, 'scripts/generate-changelog.mjs'))
  git(repo, ['init', '-q'])
  git(repo, ['config', 'user.name', 'Changelog fixture'])
  git(repo, ['config', 'user.email', 'fixture@example.test'])
  mkdirSync(path.join(repo, '.git', 'fixture-hooks'))
  git(repo, ['config', 'core.hooksPath', path.join(repo, '.git', 'fixture-hooks')])
  commit(repo, 'chore: baseline')
  return repo
}

function commit(repo, subject, date = '2026-01-01', body = '') {
  const timestamp = `${date}T12:00:00Z`
  git(repo, ['commit', '-q', '--allow-empty', '-m', `${subject}${body ? `\n\n${body}` : ''}`], {
    GIT_AUTHOR_DATE: timestamp, GIT_COMMITTER_DATE: timestamp,
  })
}

function run(repo, args = []) {
  return spawnSync(process.execPath, [path.join(repo, 'scripts/generate-changelog.mjs'), ...args], {
    cwd: temporary, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
  })
}

function ok(result) {
  assert.equal(result.status, 0, result.stderr)
  return result.stdout
}

function tree(directory) {
  const files = {}
  function visit(current, relative = '') {
    if (!existsSync(current)) return
    for (const entry of readdirSync(current).sort()) {
      const file = path.join(current, entry)
      const name = path.posix.join(relative, entry)
      if (lstatSync(file).isDirectory()) visit(file, name)
      else files[name] = readFileSync(file, 'utf8')
    }
  }
  visit(path.join(directory, 'docs', 'changelog'), 'docs/changelog')
  if (existsSync(path.join(directory, 'CHANGELOG.md'))) files['CHANGELOG.md'] = readFileSync(path.join(directory, 'CHANGELOG.md'), 'utf8')
  return files
}

function generated(repo, extra = []) {
  const output = path.join(temporary, `output-${++sequence}`)
  ok(run(repo, [...extra, '--write', '--output', output]))
  return { output, files: tree(output) }
}

function boundedAndLinked(files) {
  for (const [name, content] of Object.entries(files)) {
    assert.ok(content.endsWith('\n'), `${name}: final newline`)
    assert.ok(content.split('\n').length - 1 <= 199, `${name}: exceeds 199 physical lines`)
    for (const match of content.matchAll(/\]\(([^)]+\.md)\)/g)) {
      const destination = path.posix.normalize(path.posix.join(path.posix.dirname(name), match[1]))
      assert.ok(Object.hasOwn(files, destination), `${name}: unresolved ${destination}`)
    }
  }
}

function orderedEntries(files, name = 'CHANGELOG.md') {
  const content = files[name]
  const entries = content.split('\n').filter((line) => /^- (feat|fix)(\([^)]+\))?!?: /.test(line))
  if (entries.length) return entries
  return [...content.matchAll(/\]\(([^)]+\.md)\)/g)].flatMap((match) =>
    orderedEntries(files, path.posix.normalize(path.posix.join(path.posix.dirname(name), match[1]))),
  )
}

function test(name, fn) {
  try { fn(); passed++; console.log(`PASS: ${name}`) }
  catch (error) { failed++; console.error(`FAIL: ${name}\n${error.stack}`) }
}

try {
  test('literal history preserves releases, mixed feat/fix order, dates and subject-only behavior', () => {
    const repo = fixture()
    commit(repo, 'feat(core): 첫 기능', '2025-12-30', 'fix: body is not an entry\nSecond body line')
    commit(repo, 'fix!: old break', '2025-12-31')
    git(repo, ['tag', 'v1.0.0'])
    commit(repo, 'fix(api): new repair', '2026-01-02')
    commit(repo, 'feat: newest feature', '2026-01-03')
    commit(repo, 'docs: release prep', '2026-01-04')
    git(repo, ['tag', 'v1.1.0'])
    const { files } = generated(repo)
    assert.equal(files['docs/changelog/2025/v1.0.0.md'], `# v1.0.0 - 2025-12-31\n\n${marker}\n\n- fix!: old break\n- feat(core): 첫 기능\n`)
    assert.equal(files['docs/changelog/2026/v1.1.0.md'], `# v1.1.0 - 2026-01-04\n\n${marker}\n\n- feat: newest feature\n- fix(api): new repair\n`)
    assert.deepEqual(orderedEntries(files), ['- feat: newest feature', '- fix(api): new repair', '- fix!: old break', '- feat(core): 첫 기능'])
    boundedAndLinked(files)
  })

  test('stdout is only the root index; check never creates or changes files', () => {
    const repo = fixture()
    commit(repo, 'feat: note')
    git(repo, ['tag', 'v1.0.0'])
    const before = git(repo, ['status', '--porcelain'])
    const stdout = ok(run(repo))
    assert.match(stdout, /docs\/changelog\//)
    assert.equal(existsSync(path.join(repo, 'CHANGELOG.md')), false)
    assert.equal(run(repo, ['--check']).status, 1)
    assert.equal(existsSync(path.join(repo, 'docs')), false)
    assert.equal(git(repo, ['status', '--porcelain']), before)
    const { output, files } = generated(repo)
    assert.equal(stdout, files['CHANGELOG.md'])
    const snapshot = tree(output)
    ok(run(repo, ['--check', '--output', output]))
    assert.deepEqual(tree(output), snapshot)
    writeFileSync(path.join(output, 'docs/changelog/2026/v1.0.0.md'), `${marker}\ncorrupt\n`)
    const dirty = tree(output)
    assert.equal(run(repo, ['--check', '--output', output]).status, 1)
    assert.deepEqual(tree(output), dirty)
  })

  test('candidate keeps feat/fix date through prep and existing tag; older candidate baseline stays original', () => {
    const repo = fixture()
    commit(repo, 'feat: base', '2025-12-31')
    git(repo, ['tag', 'v1.0.0'])
    commit(repo, 'fix: candidate note', '2026-01-02')
    const before = generated(repo, ['--release', 'v1.1.0']).files
    commit(repo, 'docs: prep', '2026-01-03')
    const after = generated(repo, ['--release', 'v1.1.0']).files
    assert.deepEqual(after, before)
    assert.match(after['docs/changelog/2026/v1.1.0.md'], /^# v1\.1\.0 - 2026-01-02\n/)
    git(repo, ['tag', 'v1.1.0'])
    assert.deepEqual(generated(repo, ['--release', 'v1.1.0']).files, before)
    commit(repo, 'feat: later version', '2026-01-04')
    git(repo, ['tag', 'v2.0.0'])
    const oldCandidate = generated(repo, ['--release', 'v1.1.0']).files
    assert.deepEqual(orderedEntries(oldCandidate), ['- fix: candidate note', '- feat: later version', '- feat: base'])
    assert.equal(orderedEntries(oldCandidate).filter((line) => line === '- fix: candidate note').length, 1)
  })

  test('199-line leaf fits; 200-line release splits without squeezing or losing entries', () => {
    const repo = fixture()
    const subjects = []
    for (let i = 1; i <= 195; i++) { const subject = `fix: boundary ${i}`; subjects.unshift(`- ${subject}`); commit(repo, subject) }
    git(repo, ['tag', 'v1.0.0'])
    const at199 = generated(repo).files
    assert.equal(at199['docs/changelog/2026/v1.0.0.md'].split('\n').length - 1, 199)
    commit(repo, 'feat: line 200')
    git(repo, ['tag', '-d', 'v1.0.0'])
    git(repo, ['tag', 'v1.0.0'])
    const at200 = generated(repo).files
    assert.deepEqual(orderedEntries(at200), ['- feat: line 200', ...subjects])
    assert.ok(Object.keys(at200).includes('docs/changelog/2026/v1.0.0/entries-002.md'))
    boundedAndLinked(at199)
    boundedAndLinked(at200)
  })

  test('large release index paginates and preserves every expected release, including nonmonotonic years', () => {
    const repo = fixture()
    const expected = []
    for (let i = 1; i <= 202; i++) {
      const subject = `feat: release ${i}`
      expected.unshift(`- ${subject}`)
      commit(repo, subject, i % 2 ? '2025-01-01' : '2026-01-01')
      git(repo, ['tag', `v1.${i}.0`])
    }
    const { output, files } = generated(repo)
    assert.equal(Object.keys(files).filter((name) => /\/v1\.[0-9]+\.0\.md$/.test(name)).length, 202)
    assert.deepEqual(orderedEntries(files), expected)
    boundedAndLinked(files)
    ok(run(repo, ['--write', '--output', output]))
    assert.deepEqual(tree(output), files)
    ok(run(repo, ['--check', '--output', output]))
  })

  test('a huge real release also paginates its chunk index without losing entries', () => {
    const repo = fixture()
    const branch = git(repo, ['symbolic-ref', 'HEAD'])
    const baseline = git(repo, ['rev-parse', 'HEAD'])
    const expected = []
    const records = []
    // 194 entry pages overflow the release index after its two introductory lines.
    // Fast-import creates actual Git commits efficiently; the generator still runs real git log.
    for (let i = 1; i <= 37830; i++) {
      const subject = `fix: huge release ${i}`
      expected.unshift(`- ${subject}`)
      records.push(`commit ${branch}\nmark :${i}\ncommitter Fixture <fixture@example.test> 1767268800 +0000\ndata ${Buffer.byteLength(subject)}\n${subject}\nfrom ${i === 1 ? baseline : `:${i - 1}`}\n\n`)
    }
    execFileSync('git', ['fast-import', '--quiet'], { cwd: repo, input: records.join(''), encoding: 'utf8' })
    git(repo, ['tag', 'v1.0.0'])
    const { output, files } = generated(repo)
    assert.equal(Object.keys(files).filter((name) => /\/entries-[0-9]+\.md$/.test(name)).length, 194)
    assert.ok(Object.keys(files).some((name) => /v1\.0\.0\/index-/.test(name)))
    assert.deepEqual(orderedEntries(files), expected)
    boundedAndLinked(files)
    ok(run(repo, ['--check', '--output', output]))
  })

  test('multiline first paragraphs retain Git subject folding and literal separators', () => {
    const repo = fixture()
    commit(repo, 'fix: first line\ncontinued subject', '2026-01-01', 'feat: body excluded')
    commit(repo, 'feat(core): literal \x1f separator', '2026-01-02')
    git(repo, ['tag', 'v1.0.0'])
    const { files } = generated(repo)
    assert.deepEqual(orderedEntries(files), ['- feat(core): literal \x1f separator', '- fix: first line continued subject'])
  })

  test('empty repositories and empty feat/fix tag ranges do not invent releases', () => {
    const repo = fixture()
    const empty = generated(repo).files
    assert.deepEqual(orderedEntries(empty), [])
    git(repo, ['tag', 'v1.0.0'])
    commit(repo, 'docs: no changelog entry')
    git(repo, ['tag', 'v1.1.0'])
    const tagged = generated(repo, ['--release', 'v1.1.0']).files
    assert.deepEqual(orderedEntries(tagged), [])
    assert.equal(Object.keys(tagged).filter((name) => /\/v.*\.md$/.test(name)).length, 0)
  })

  test('malformed release/CLI and malformed v tags fail before writes; unrelated tags are ignored', () => {
    const repo = fixture()
    for (const args of [['--release'], ['--release', 'v1.0'], ['--release', 'v1.2.3-next'], ['--release', '--all'], ['--write', '--check'], ['--output', temporary], ['--unknown'], ['--release', 'v1.0.0', '--release', 'v2.0.0']]) {
      const result = run(repo, args)
      assert.equal(result.status, 2, JSON.stringify({ args, stderr: result.stderr }))
      assert.equal(existsSync(path.join(repo, 'CHANGELOG.md')), false)
    }
    git(repo, ['tag', 'notes'])
    ok(run(repo))
    git(repo, ['tag', 'vbroken'])
    const result = run(repo, ['--write'])
    assert.equal(result.status, 1)
    assert.match(result.stderr, /vbroken/)
    assert.equal(existsSync(path.join(repo, 'CHANGELOG.md')), false)
  })

  test('stale generated files are detected and pruned; unknown user files survive', () => {
    const repo = fixture()
    commit(repo, 'fix: generated')
    git(repo, ['tag', 'v1.0.0'])
    const { output, files } = generated(repo)
    mkdirSync(path.join(output, 'docs/changelog/old'), { recursive: true })
    mkdirSync(path.join(output, 'docs/changelog/user-empty'))
    writeFileSync(path.join(output, 'docs/changelog/old/stale.md'), `# old\n\n${marker}\n`)
    writeFileSync(path.join(output, 'docs/changelog/user.md'), '# User notes\n')
    assert.equal(run(repo, ['--check', '--output', output]).status, 1)
    ok(run(repo, ['--write', '--output', output]))
    assert.equal(existsSync(path.join(output, 'docs/changelog/old')), false)
    assert.equal(existsSync(path.join(output, 'docs/changelog/user-empty')), true)
    assert.equal(readFileSync(path.join(output, 'docs/changelog/user.md'), 'utf8'), '# User notes\n')
    ok(run(repo, ['--check', '--output', output]))
    const after = tree(output)
    delete after['docs/changelog/user.md']
    assert.deepEqual(after, files)
    // Changing from split to unsplit must remove now-unreachable generated entry pages.
    const first = git(repo, ['rev-parse', 'HEAD'])
    for (let i = 0; i < 196; i++) commit(repo, `feat: extra ${i}`)
    git(repo, ['tag', '-f', 'v1.0.0'])
    ok(run(repo, ['--write', '--output', output]))
    assert.ok(existsSync(path.join(output, 'docs/changelog/2026/v1.0.0/entries-002.md')))
    git(repo, ['tag', '-f', 'v1.0.0', first])
    ok(run(repo, ['--write', '--output', output]))
    assert.equal(existsSync(path.join(output, 'docs/changelog/2026/v1.0.0')), false)
  })

  test('unknown output collisions and symlinks reject the whole write before changing anything', () => {
    const repo = fixture()
    commit(repo, 'feat: collision')
    git(repo, ['tag', 'v1.0.0'])
    const { output } = generated(repo)
    const leaf = path.join(output, 'docs/changelog/2026/v1.0.0.md')
    writeFileSync(leaf, '# Manual source\n')
    const before = tree(output)
    assert.equal(run(repo, ['--write', '--output', output]).status, 1)
    assert.deepEqual(tree(output), before)
    rmSync(leaf)
    const outside = path.join(temporary, 'outside.txt')
    writeFileSync(outside, 'untouched\n')
    symlinkSync(outside, leaf)
    assert.equal(run(repo, ['--write', '--output', output]).status, 1)
    assert.equal(run(repo, ['--check', '--output', output]).status, 1)
    assert.equal(readFileSync(outside, 'utf8'), 'untouched\n')
    rmSync(path.join(output, 'docs/changelog'), { recursive: true })
    symlinkSync(temporary, path.join(output, 'docs/changelog'))
    assert.equal(run(repo, ['--write', '--output', output]).status, 1)
  })
} finally {
  rmSync(temporary, { recursive: true, force: true })
}

console.log(`RESULT: ${passed} PASS, ${failed} FAIL`)
process.exitCode = failed ? 1 : 0
