#!/usr/bin/env node
// Shared metadata and native-runtime task sections are the only generation inputs.
import * as fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const validName = name => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) && name.length < 64
function checkedPath(root, relative) {
  const resolved = path.resolve(root, relative)
  if (!resolved.startsWith(`${root}${path.sep}`)) throw new Error(`path escapes root: ${relative}`)
  let current = root
  const components = relative.split('/')
  for (let index = 0; index < components.length; index++) {
    const component = components[index]
    current = path.join(current, component)
    if (fs.existsSync(current)) {
      const info = fs.lstatSync(current)
      if (info.isSymbolicLink()) throw new Error(`symlink path refused: ${relative}`)
      if (info.isFile() && info.nlink > 1) throw new Error(`hardlinked file refused: ${relative}`)
      if (index < components.length - 1 && !info.isDirectory()) throw new Error(`non-directory path refused: ${relative}`)
    }
  }
  return resolved
}
function metadata(file, expectedName) {
  const text = fs.readFileSync(file, 'utf8')
  const frontmatter = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(text)?.[1]
  if (!frontmatter) throw new Error(`missing frontmatter: ${file}`)
  const values = {}
  for (const key of ['name', 'description']) {
    const matches = [...frontmatter.matchAll(new RegExp(`^${key}: (.+)$`, 'gm'))]
    if (matches.length !== 1 || !matches[0][1].trim() || /^[>|]/.test(matches[0][1])) throw new Error(`expected one single-line ${key}: ${file}`)
    values[key] = matches[0][1]
  }
  if (!validName(values.name) || values.name !== expectedName) throw new Error(`invalid or mismatched skill name: ${file}`)
  return values
}
function sections(text) {
  const found = new Map()
  const matches = [...text.matchAll(/^## (.+)\n/gm)]
  for (let index = 0; index < matches.length; index++) {
    const name = matches[index][1]
    const body = text.slice(matches[index].index + matches[index][0].length, matches[index + 1]?.index ?? text.length).trim()
    if (found.has(name) || !body) throw new Error(`duplicate or empty native section: ${name}`)
    found.set(name, body)
  }
  return found
}
export function renderCodexSkills(root = repositoryRoot) {
  root = path.resolve(root)
  if (!fs.statSync(root).isDirectory() || fs.realpathSync(root) !== root) throw new Error('root must be a real directory without symlink components')
  const prefix = 'plugins/harness-guard'
  const sources = checkedPath(root, `${prefix}/skills`)
  const output = checkedPath(root, `${prefix}/codex/skills`)
  const native = sections(fs.readFileSync(checkedPath(root, `${prefix}/codex/native-runtime.md`), 'utf8'))
  if (!native.has('공통 실행')) throw new Error('missing native common section')
  const names = fs.readdirSync(sources).filter(name => {
    const entry = checkedPath(root, `${prefix}/skills/${name}`)
    return fs.statSync(entry).isDirectory()
  }).sort()
  if (!names.length) throw new Error('no shared skills')
  const rendered = names.map(name => {
    if (!validName(name)) throw new Error(`invalid skill directory: ${name}`)
    const data = metadata(checkedPath(root, `${prefix}/skills/${name}/SKILL.md`), name)
    if (!native.has(name)) throw new Error(`missing native task section: ${name}`)
    const destination = checkedPath(root, `${prefix}/codex/skills/${name}/SKILL.md`)
    const content = `---\nname: ${data.name}\ndescription: ${data.description}\n---\n\n<!-- Generated by scripts/generate-codex-skills.mjs; edit shared frontmatter or codex/native-runtime.md. -->\n\n# ${name} — Codex native wrapper\n\n먼저 [공용 스킬](../../../skills/${name}/SKILL.md)을 끝까지 읽고 적용한다.\n\n## Codex 실행\n\n[공통 실행](../../native-runtime.md#공통-실행)과 [${name} 실행](../../native-runtime.md#${name}) 절만 읽고 함께 적용한다.\n`
    return { path: destination, content }
  })
  if (fs.existsSync(output)) {
    for (const name of fs.readdirSync(output)) {
      checkedPath(root, `${prefix}/codex/skills/${name}`)
      if (!names.includes(name)) throw new Error(`orphan native wrapper: ${name}`)
    }
  }
  return rendered
}
export function generateCodexSkills({ root = repositoryRoot, write = false } = {}) {
  const rendered = renderCodexSkills(root) // Validate every source/path before any output mutation.
  const stale = rendered.filter(file => !fs.existsSync(file.path) || fs.readFileSync(file.path, 'utf8') !== file.content)
  if (write) {
    for (const file of stale) {
      fs.mkdirSync(path.dirname(file.path), { recursive: true })
      fs.writeFileSync(file.path, file.content)
    }
  } else if (stale.length) throw new Error(`stale Codex wrappers: ${stale.map(file => path.relative(root, file.path)).join(', ')}; run node scripts/generate-codex-skills.mjs --write`)
  return rendered.length
}
function main(argv) {
  const mode = argv.shift()
  if (!['--check', '--write'].includes(mode)) throw new Error('usage: generate-codex-skills.mjs --check|--write [--root DIRECTORY]')
  let root = repositoryRoot
  if (argv.length) {
    if (argv.length !== 2 || argv[0] !== '--root' || !path.isAbsolute(argv[1])) throw new Error('expected --root with an absolute directory')
    root = argv[1]
  }
  const count = generateCodexSkills({ root, write: mode === '--write' })
  console.log(`${mode === '--write' ? 'Generated' : 'Verified'} ${count} Codex skill wrappers`)
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)) }
  catch (error) { console.error(`generate-codex-skills: ${error.message}`); process.exitCode = 1 }
}
