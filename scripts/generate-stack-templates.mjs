#!/usr/bin/env node
// Concatenate reviewed YAML sources without parsing or rewriting workflow values.
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadCatalog, parseSelectionArgs, repositoryRoot, selectStack } from './stack-catalog.mjs';

export const generatedBanner = '# Generated by scripts/generate-stack-templates.mjs; edit templates/ci/stacks/sources/ and templates/stacks.json.\n';

function inside(directory, relative) {
  if (typeof relative !== 'string' || relative.length === 0) throw new Error('Invalid catalog path');
  const target = resolve(directory, relative);
  if (!target.startsWith(`${directory}${sep}`)) throw new Error(`Catalog path escapes directory: ${relative}`);
  return target;
}

export function renderTemplates(root = repositoryRoot) {
  const catalog = loadCatalog(root);
  const directory = resolve(root, 'templates/ci/stacks');
  const sources = resolve(directory, 'sources');
  const read = relative => readFileSync(inside(sources, relative), 'utf8');
  const seen = new Set();
  return catalog.stacks.map(stack => {
    if (!/^ci-gate-[a-z-]+\.yml$/.test(stack.template) || seen.has(stack.template)) {
      throw new Error(`Invalid or duplicate template: ${stack.template}`);
    }
    seen.add(stack.template);
    return {
      path: inside(directory, stack.template),
      content: generatedBanner + read(stack.sources.header) + read(catalog.commonSources.workflow)
        + stack.sources.jobs.map(job => read(job) + '\n').join('') + read(catalog.commonSources.secretScan),
    };
  });
}

function composeJob(source, role, directory) {
  if (!source.startsWith('  quality:\n') || (source.match(/^  [a-z-]+:/gm) ?? []).length !== 1) {
    throw new Error('Composition requires one standalone quality job');
  }
  // Keep reviewed commands, services, env and action SHAs intact. Only adapt job paths.
  let job = source.replace(/^  quality:/, `  ${role}:`);
  const pathValue = /^[0-9]/.test(directory) || /^(?:null|true|false|yes|no|on|off|y|n)$/i.test(directory)
    ? JSON.stringify(directory) : directory;
  if (/^    defaults:/m.test(job)) {
    if (!/^    defaults:\n      run:\n        working-directory: [^\n]+$/m.test(job)) {
      throw new Error('Unsupported standalone working-directory defaults');
    }
    job = job.replace(/^(        working-directory: )[^\n]+$/m, `$1${pathValue}`);
  } else {
    if (!/^    steps:/m.test(job)) throw new Error('Standalone job has no steps');
    job = job.replace(/^    steps:/m,
      `    defaults:\n      run:\n        working-directory: ${pathValue}\n\n    steps:`);
  }
  if (/uses: actions\/setup-node@/.test(job)) {
    job = job.replace(/^(          cache: npm[^\n]*\n)/m,
      `$1          cache-dependency-path: ${directory}/package-lock.json\n`);
  }
  if (/uses: ruby\/setup-ruby@/.test(job)) {
    job = job.replace(/^(          bundler-cache: true[^\n]*\n)/m,
      `$1          working-directory: ${pathValue}\n`);
  }
  return job;
}

export function renderComposition(selection, options = {}, root = repositoryRoot) {
  const catalog = loadCatalog(root);
  const selected = selectStack(selection, options, catalog);
  if (selected.mode !== 'composed') throw new Error('Composition requires backend+frontend');
  const sources = resolve(root, 'templates/ci/stacks/sources');
  const read = relative => readFileSync(inside(sources, relative), 'utf8');
  const jobs = ['backend', 'frontend'].map(role => {
    const stack = catalog.stacks.find(entry => entry.id === selected[role].id);
    if (stack.sources.jobs.length !== 1) throw new Error('Composition requires one standalone job source');
    return composeJob(read(stack.sources.jobs[0]), role, selected[role].directory);
  });
  return generatedBanner + `# ci-gate — ${selected.backend.key} backend + ${selected.frontend.key} frontend\n`
    + read(catalog.commonSources.workflow) + jobs.map(job => job + '\n').join('')
    + read(catalog.commonSources.secretScan);
}

export function generateTemplates(mode, root = repositoryRoot) {
  if (!['--write', '--check'].includes(mode)) throw new Error('Usage: generate-stack-templates.mjs --write | --check');
  const outputs = renderTemplates(root);
  const drift = [];
  for (const output of outputs) {
    if (mode === '--write') writeFileSync(output.path, output.content);
    else {
      let current;
      try { current = readFileSync(output.path, 'utf8'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (current !== output.content) drift.push(output.path);
    }
  }
  if (drift.length) throw new Error(`Stack template drift:\n${drift.join('\n')}\nRun node scripts/generate-stack-templates.mjs --write`);
  return outputs.length;
}

if (process.argv[1] && existsSync(process.argv[1]) && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args[0] === '--compose') {
      const { selection, options } = parseSelectionArgs(args.slice(1));
      process.stdout.write(renderComposition(selection, options));
    } else {
      if (args.length !== 1) throw new Error('Usage: generate-stack-templates.mjs --write | --check | --compose <backend+frontend> [--backend-dir relative] [--frontend-dir relative]');
      const count = generateTemplates(args[0]);
      console.log(`Stack templates ${args[0].slice(2)}: ${count} files`);
    }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
